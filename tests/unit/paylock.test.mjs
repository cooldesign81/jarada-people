import { makeLock, verifyLock, deriveHash, checkNewPassword, newSalt } from "../../js/paylock-crypto.js";
let f = 0; const eq = (n, a, b) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) f++; console.log(ok ? "PASS" : "FAIL", n, ok ? "" : JSON.stringify(a) + " != " + JSON.stringify(b)); };
const lock = await makeLock("correct-horse-9");
eq("lock fields", [typeof lock.salt, typeof lock.hash, lock.iter, lock.algo], ["string", "string", 200000, "PBKDF2-SHA256"]);
eq("hash does not contain password", JSON.stringify(lock).includes("correct-horse"), false);
eq("verify ok", await verifyLock(lock, "correct-horse-9"), true);
eq("verify wrong", await verifyLock(lock, "correct-horse-8"), false);
eq("verify empty", await verifyLock(lock, ""), false);
eq("verify case sensitive", await verifyLock(lock, "Correct-horse-9"), false);
eq("verify missing lock", await verifyLock(null, "x"), false);
eq("verify korean password", await verifyLock(await makeLock("비밀번호테스트!1"), "비밀번호테스트!1"), true);
eq("different salt each time", (await makeLock("same-pass-1")).hash !== (await makeLock("same-pass-1")).hash, true);
const s = newSalt(); eq("deterministic with same salt", await deriveHash("abc12345", s), await deriveHash("abc12345", s));
eq("rule: too short", checkNewPassword("abc12"), "비밀번호는 8자 이상이어야 합니다.");
eq("rule: digits only", checkNewPassword("12345678").includes("숫자만"), true);
eq("rule: repeated", checkNewPassword("aaaaaaaa").includes("반복"), true);
eq("rule: mismatch", checkNewPassword("abcdefg1", "abcdefg2").includes("일치"), true);
eq("rule: ok", checkNewPassword("abcdefg1", "abcdefg1"), "");
process.exit(f ? 1 : 0);
